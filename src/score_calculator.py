def calculate_score(value, weights):
    w1 = weights['w1']
    w2 = weights['w2']
    w3 = weights['w3']
    w2_sp = weights['w2_sp']
    w3_sp = weights['w3_sp']
    
    if w2_sp is not None:
        if value <= 6:
            return (value - 1) * w1
        elif value <= 10:
            return 5 * w1 + (value - 4) * w2_sp
        else:
            final_w3 = w3_sp if w3_sp is not None else w3
            return 5 * w1 + 4 * w2_sp + (value - 10) * final_w3
    else:
        if value <= 6:
            return (value - 1) * w1
        elif value <= 12:
            return 5 * w1 + (value - 6) * w2
        else:
            return 5 * w1 + 6 * w2 + (value - 12) * w3

def calculate_total_score(attributes):
    normal_attrs = [attr for attr in REQUIRED_ATTRIBUTES if attr not in HIDDEN_ATTRIBUTES]
    
    has_all_normal = all(attr in attributes for attr in normal_attrs)
    if not has_all_normal:
        return None, None, None
    
    normal_score = 0
    hidden_score = 0
    
    for attr, value in attributes.items():
        if attr in ATTRIBUTE_WEIGHTS:
            if attr in HIDDEN_ATTRIBUTES:
                hidden_score += calculate_score(value, ATTRIBUTE_WEIGHTS[attr])
            else:
                normal_score += calculate_score(value, ATTRIBUTE_WEIGHTS[attr])
    
    for attr in HIDDEN_ATTRIBUTES:
        if attr not in attributes:
            pass
    
    return normal_score, hidden_score, normal_score + hidden_score

